export class Brand {
  constructor(slug) {
    this.slug = slug;
    this.dir = path.join(ROOT, "brands", slug);
    const f = path.join(this.dir, "brand.yaml");
    if (!exists(f)) throw new Error(`Brand '${slug}' not found. Create it: node tools/reel.mjs new-brand ${slug}`);
    this.data = readYaml(f);
  }
  get(...keys) { return getPath(this.data, keys.join(".")); }
  get name() { return this.data.name ?? this.slug; }
  color(token) { return token?.startsWith?.("#") ? token : this.get("colors", token); }
  resolve(relPath) {
    if (!relPath) return null;
    for (const base of [this.dir, ROOT]) { const p = path.join(base, relPath); if (exists(p)) return p; }
    return null;
  }
  hasLogo() { return !!this.resolve(this.get("logo")); }
  /** Replace {name}, {url}, {tagline}, {handle}, {descriptor}... with brand strings. */
  fmt(s) {
    if (typeof s !== "string") return s;
    for (const [k, v] of Object.entries(this.data)) if (["string", "number"].includes(typeof v)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }
}

export function listBrands() {
  return fs.readdirSync(path.join(ROOT, "brands"), { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_")).map((d) => d.name).sort();
}

const fontFace = (family, file, weight) =>
  `@font-face { font-family: "${family}"; src: url("fonts/${path.basename(file)}") format("truetype"); font-weight: ${weight}; font-style: normal; font-display: block; }`;

/** assets/brand/tokens.css : brand colors, fonts (shipped as files) and per-format safe-zone variables. */
export function buildTokens(brand, formatKey) {
  const c = brand.get("colors") ?? {};
  const f = FORMATS[formatKey];
  const hf = brand.resolve(brand.get("fonts", "heading")), bf = brand.resolve(brand.get("fonts", "body"));
  const faces = [hf && fontFace("BrandHeading", hf, 700), bf && fontFace("BrandBody", bf, 300)].filter(Boolean).join("\n");
  return `/* GENERATED by reel-studio from brands/${brand.slug}/brand.yaml. Do not edit: run \`reel sync\`. */
${faces}
:root {
  --brand-bg: ${c.bg}; --brand-surface: ${c.surface}; --brand-accent: ${c.accent};
  --brand-text: ${c.text}; --brand-muted: ${c.muted};
  --font-heading: "BrandHeading", system-ui, sans-serif;
  --font-body: "BrandBody", system-ui, sans-serif;
  /* safe zone for ${f.label}: keep key content inside these insets */
  --canvas-w: ${f.w}px; --canvas-h: ${f.h}px;
  --safe-top: ${f.safe.top}px; --safe-bottom: ${f.safe.bottom}px; --safe-side: ${f.safe.side}px;
}
.safe { position: absolute; top: var(--safe-top); bottom: var(--safe-bottom); left: var(--safe-side); right: var(--safe-side); }
`;
}

export function fontFiles(brand) {
  return [brand.get("fonts", "heading"), brand.get("fonts", "body")].map((r) => brand.resolve(r)).filter(Boolean);
}

/** frame.md : the design-truth file HyperFrames workflows read (palette, type ramp, components, composition rules). */
export function buildFrame(brand, brief) {
  const fk = getPath(brief, "format.preset", "feed_4x5"), f = FORMATS[fk];
  const sp = getPath(brief, "style.preset", "precise"), en = getPath(brief, "style.energy", "medium");
  const S = STYLE_PRESETS[sp], E = ENERGY[en];
  const c = brand.get("colors") ?? {};
  const scale = f.h / 1350;
  return `# frame.md: ${brand.name} (${f.label}, ${f.w}x${f.h})

> GENERATED by reel-studio from brands/${brand.slug}/brand.yaml + the project's brief. This is a **style spec, not copy**: never lift words or labels from it into the video.
> Regenerate with \`node tools/reel.mjs sync <project>\`. Brand-level edits belong in brand.yaml.

## Look
- **Positioning:** ${brand.get("positioning") ?? ""}
- **Motion personality (brand):** ${brand.get("style", "motion") ?? ""}
- **Visual language:** ${brand.get("style", "visual_language") ?? ""}
- **Style preset for this piece: ${sp}** (${S.note})
- **Energy: ${en}** (${E.note})

## Palette (use CSS variables from \`assets/brand/tokens.css\`)
| Role | Variable | Value |
|---|---|---|
| Background | \`--brand-bg\` | ${c.bg} |
| Surface / shapes | \`--brand-surface\` | ${c.surface} |
| Accent (the one color that pops; max ~15% of the frame) | \`--brand-accent\` | ${c.accent} |
| Text | \`--brand-text\` | ${c.text} |
| Muted text | \`--brand-muted\` | ${c.muted} |

## Typography (fonts ship as files in \`assets/brand/fonts/\`; the @font-face rules are in tokens.css)
- **Headings:** \`var(--font-heading)\`, bold. **Body/labels:** \`var(--font-body)\`.
- Type ramp for ${f.w} px width: hero ${Math.round(140)}-${Math.round(160)} px (hook slams) | headline ${96}-${120} px | subhead 56-64 px | body 40 px | captions ~54 px | absolute minimum 26 px.
- Hook text: max 4 words per beat. Never more than ~100 characters on screen at once.

## Components
- **Hook slam:** one big phrase, centered, replaces the previous one (cut on the beat).
- **Accent highlight:** the key word/number in \`--brand-accent\`.
- **CTA card:** URL / handle in accent, wordmark or logo above, holds for the last 2-3 s.
- **Caption pill:** semi-opaque \`--brand-bg\` pill, text ~54 px, the spoken word highlighted in accent (only when captions are on).

## Composition rules
- Canvas ${f.w}x${f.h}. **Keep key content inside the safe zone:** top ${f.safe.top}px, bottom ${f.safe.bottom}px, sides ${f.safe.side}px (\`.safe\` wrapper class exists in tokens.css).
- Full-bleed background goes on a dedicated full-duration \`class="clip"\` layer, never on \`#root\`.
- Use only the brand fonts above (they ship as files). Colors only via the variables.
- Layout positions are authored for 1080x1350; this piece's height scale is ${scale.toFixed(2)}x.

## Motion (${sp})
- **Easing:** ${S.ease}
- **Entrances:** ${S.entrance}
- **Camera:** ${S.camera}
- **Beat punch:** ${S.punch}
- **Transitions:** ${S.transitions}
- **Vignette:** ${S.vignette} | **Type scale:** ${S.typeScale}
- Everything must be seek-safe (paused GSAP timeline, no randomness, no timers, no onUpdate, no infinite loops).
`;
}

/** Tiny placeholder logos as SVG (no dependencies). Clearly flagged in brand.yaml as placeholders. */
export function genAsset(brand, kind) {
  const c = brand.get("colors") ?? {};
  const assets = path.join(brand.dir, "assets");
  fs.mkdirSync(assets, { recursive: true });
  let svg;
  if (kind === "monogram") {
    const ini = brand.name.split(/\s+/).slice(0, 2).map((w) => w[0]).join("").toUpperCase();
    svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 600"><circle cx="300" cy="300" r="280" fill="${c.accent}"/><text x="300" y="360" text-anchor="middle" font-family="Poppins, Arial, sans-serif" font-weight="700" font-size="260" fill="${c.bg}">${ini}</text></svg>`;
  } else if (kind === "wordmark") {
    const size = Math.max(60, Math.min(200, Math.floor(1400 / Math.max(brand.name.length, 4) * 1.5)));
    svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 360"><text x="780" y="220" text-anchor="middle" font-family="Poppins, Arial, sans-serif" font-weight="700" font-size="${size}" fill="${c.text}">${brand.name}</text><circle cx="1500" cy="250" r="${Math.round(size * 0.11)}" fill="${c.accent}"/></svg>`;
  } else throw new Error("kind must be wordmark | monogram");
  const out = path.join(assets, "logo.svg");
  fs.writeFileSync(out, svg);
  const f = path.join(brand.dir, "brand.yaml");
  let y = fs.readFileSync(f, "utf8");
  const line = `logo: assets/logo.svg   # GENERATED PLACEHOLDER: replace with the real logo when available`;
  y = /^logo:.*$/m.test(y) ? y.replace(/^logo:.*$/m, line) : y + `\n${line}\n`;
  fs.writeFileSync(f, y);
  return out;
}

export async function fetchAssets(brand) {
  const list = brand.get("assets") ?? [];
  const out = [];
  for (const it of list) {
    const dest = path.join(brand.dir, it.save_as);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    try {
      const r = await fetch(it.url, { headers: { "User-Agent": "Mozilla/5.0" } });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      fs.writeFileSync(dest, Buffer.from(await r.arrayBuffer()));
      out.push(`saved ${dest}`);
    } catch (e) { out.push(`FAILED ${it.url}: ${e.message}`); }
  }
  return out;
}
